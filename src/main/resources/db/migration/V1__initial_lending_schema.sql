CREATE TABLE student (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL CHECK (char_length(name) BETWEEN 1 AND 120),
    email VARCHAR(254) NOT NULL UNIQUE CHECK (char_length(email) BETWEEN 1 AND 254)
);

CREATE TABLE equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_code VARCHAR(50) NOT NULL UNIQUE CHECK (char_length(inventory_code) BETWEEN 1 AND 50),
    name VARCHAR(120) NOT NULL CHECK (char_length(name) BETWEEN 1 AND 120),
    category VARCHAR(60) NOT NULL CHECK (char_length(category) BETWEEN 1 AND 60),
    description VARCHAR(1000) CHECK (description IS NULL OR char_length(description) <= 1000)
);

CREATE TABLE loan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES student (id) ON DELETE RESTRICT,
    equipment_id BIGINT NOT NULL REFERENCES equipment (id) ON DELETE RESTRICT,
    borrowing_date DATE NOT NULL,
    due_date DATE NOT NULL,
    return_date DATE,
    CONSTRAINT chk_loan_due_after_borrowing CHECK (due_date > borrowing_date),
    CONSTRAINT chk_loan_return_not_before_borrowing CHECK (return_date IS NULL OR return_date >= borrowing_date)
);

CREATE INDEX ix_loan_student_id ON loan (student_id);
CREATE INDEX ix_loan_equipment_id ON loan (equipment_id);
CREATE UNIQUE INDEX ux_loan_active_equipment ON loan (equipment_id) WHERE return_date IS NULL;
